/** Local tangent plane origin. Equirectangular km are exact to < 0.1% across the strait. */
export const ORIGIN: LatLon = [41.1, 29.06];
const KM_PER_DEG_LAT = 110.574;
const KM_PER_DEG_LON = 111.32 * Math.cos((ORIGIN[0] * Math.PI) / 180);

/** Latitude/longitude → km east / km north of `ORIGIN`. */
export function toKm([lat, lon]: LatLon): [number, number] {
  return [(lon - ORIGIN[1]) * KM_PER_DEG_LON, (lat - ORIGIN[0]) * KM_PER_DEG_LAT];
}
