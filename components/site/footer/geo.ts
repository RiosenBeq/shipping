/**
 * The Bosphorus for the footer's night chart (DESIGN-V2 §9, docs/REDESIGN.md §11): both shores
 * from the Sea of Marmara to the Black Sea, as latitude/longitude key points.
 *
 * How the channel was derived (server-side data, never shipped to the browser):
 * - **Shores**: the water/land edge of the OpenStreetMap standard map at zoom 12 (≈ 29 m per
 *   pixel; © OpenStreetMap contributors, ODbL — credited under the chart), traced once and
 *   generalised with Ramer–Douglas–Peucker (tolerance ≈ 32 m) to the points below. The European
 *   shore runs Marmara → Seraglio Point → round the Golden Horn → up the Bosphorus → west along
 *   the Black Sea coast; the Asian shore runs Moda → Üsküdar → up the Bosphorus → east along the
 *   Black Sea coast. Rounded to 4 decimals (≈ 10 m).
 * - **Landmarks** (bridges, Maiden's Tower, the bends): Wikidata coordinates (CC0), rounded.
 * - **Centreline and lanes**: computed in `chart.ts` from the two shores (a guide line moved to
 *   the midpoints of the nearest European and Asian shore points, iterated), not drawn by hand.
 *
 * A generalised illustration, not a navigational chart.
 */

