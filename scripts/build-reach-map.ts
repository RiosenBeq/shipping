/**
 * Generates components/site/home/reach-map.ts: the halftone dot map of the
 * homepage's Reach card (DESIGN-V2 §7.6) — land from Natural Earth 1:50m
 * (public domain, naturalearthdata.com), Europe → Singapore, Mercator, one
 * dot per grid cell whose centre is on land.
 *
 *   npx vite-node scripts/build-reach-map.ts -- [path/to/ne_50m_land.geojson]
 *
 * Without a path it downloads ne_50m_land.geojson from the Natural Earth
 * repository on GitHub. The output is a few kilobytes of SVG path data
 * (one "m dx 0 h0" per dot, drawn with round line caps), so the map costs no
 * request and no client JavaScript.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

type Ring = [number, number][];
type Geo = {
  features: { geometry: { type: "Polygon" | "MultiPolygon"; coordinates: unknown } }[];
};

const SOURCE =
  "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_land.geojson";

/** The crop (degrees) and the grid. */
const LON0 = -11;
const LON1 = 107;
const LAT0 = -5;
const LAT1 = 57;
const COLS = 88;

const merc = (lat: number) => Math.log(Math.tan(Math.PI / 4 + (lat * Math.PI) / 360));
const Y0 = merc(LAT1);
const Y1 = merc(LAT0);
const X_SPAN = ((LON1 - LON0) * Math.PI) / 180;
const CELL = X_SPAN / COLS;
const ROWS = Math.round((Y0 - Y1) / CELL);

/** Projected grid units: x 0..COLS, y 0..ROWS (top = north). */
export function project(lon: number, lat: number): [number, number] {
  return [(((lon - LON0) * Math.PI) / 180) / CELL, (Y0 - merc(lat)) / CELL];
}
function unproject(x: number, y: number): [number, number] {
  const lon = LON0 + ((x * CELL) * 180) / Math.PI;
  const m = Y0 - y * CELL;
  const lat = ((2 * Math.atan(Math.exp(m)) - Math.PI / 2) * 180) / Math.PI;
  return [lon, lat];
}

function inRing(lon: number, lat: number, ring: Ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

async function load(file?: string): Promise<Geo> {
  if (file) return JSON.parse(readFileSync(file, "utf8")) as Geo;
  const res = await fetch(SOURCE);
  if (!res.ok) throw new Error(`download failed: ${res.status}`);
  return (await res.json()) as Geo;
}

async function main() {
  const file = process.argv.slice(2).find((a) => a !== "--");
  const geo = await load(file);
  const polys: Ring[][] = [];
  for (const f of geo.features) {
    const g = f.geometry;
    const list = (g.type === "Polygon" ? [g.coordinates] : g.coordinates) as Ring[][];
    for (const p of list) {
      const outer = p[0];
      const lons = outer.map((c) => c[0]);
      const lats = outer.map((c) => c[1]);
      if (Math.max(...lons) < LON0 - 2 || Math.min(...lons) > LON1 + 2) continue;
      if (Math.max(...lats) < LAT0 - 2 || Math.min(...lats) > LAT1 + 2) continue;
      polys.push(p);
    }
  }
  const land = (lon: number, lat: number) =>
    polys.some((p) => inRing(lon, lat, p[0]) && !p.slice(1).some((h) => inRing(lon, lat, h)));

  // One path: per row "M x y h0" for the first dot, then "m dx 0 h0".
  let d = "";
  let dots = 0;
  for (let r = 0; r < ROWS; r++) {
    let last = -1;
    for (let c = 0; c < COLS; c++) {
      const [lon, lat] = unproject(c + 0.5, r + 0.5);
      if (!land(lon, lat)) continue;
      d += last < 0 ? `M${c} ${r}h0` : `m${c - last} 0h0`;
      last = c;
      dots++;
    }
  }

  const out = `/**
 * GENERATED by scripts/build-reach-map.ts — do not edit by hand.
 *
 * Halftone land of the Reach map (DESIGN-V2 §7.6): Natural Earth 1:50m land
 * (public domain), Mercator, ${LON0}°…${LON1}°E × ${LAT0}°…${LAT1}°N, a ${COLS} × ${ROWS} grid
 * (${dots} dots). Draw \`LAND_DOTS\` as a stroked path with round caps; one grid
 * unit = one cell. \`project\` turns lon/lat into the same grid units.
 */
export const MAP_COLS = ${COLS};
export const MAP_ROWS = ${ROWS};
export const LAND_DOTS =
  "${d}";

const LON0 = ${LON0};
const CELL = ${CELL};
const Y0 = ${Y0};
const merc = (lat: number) => Math.log(Math.tan(Math.PI / 4 + (lat * Math.PI) / 360));

/** lon/lat (degrees) → grid units (x right, y down), the frame of LAND_DOTS. */
export function project(lon: number, lat: number): [number, number] {
  return [((lon - LON0) * Math.PI) / 180 / CELL, (Y0 - merc(lat)) / CELL];
}
`;
  const target = path.join(process.cwd(), "components/site/home/reach-map.ts");
  writeFileSync(target, out);
  console.log(`wrote ${target}: ${COLS}×${ROWS}, ${dots} dots, ${d.length} chars`);
}

void main();
